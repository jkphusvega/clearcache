"""Fixture for M3 verification 4-1 (eng review D3, D14): many small JS projects.

Creates C:\\ClearCache_TestZone\\bench-node-modules-<N>\\projects\\gXX\\pYYY with package.json,
src\\index.js and a node_modules holding a few packages (one with its own nested node_modules).
The same fixture is scanned before (M2 baseline, T3) and after (T8) the rule changes.

    python scripts/bench/make_node_modules_fixture.py [--projects 3000]
"""

import argparse
import os
import shutil

BASE = r"C:\ClearCache_TestZone"
PER_GROUP = 100
PACKAGES = ["alpha", "beta", "gamma", "delta", "epsilon"]


def write(path: str, size: int) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(b"x" * size)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--projects", type=int, default=3000)
    args = ap.parse_args()

    root = os.path.join(BASE, f"bench-node-modules-{args.projects}")
    if os.path.exists(root):
        shutil.rmtree(root)
    for i in range(args.projects):
        proj = os.path.join(root, "projects", f"g{i // PER_GROUP:02d}", f"p{i % PER_GROUP:03d}")
        write(os.path.join(proj, "package.json"), 200)
        write(os.path.join(proj, "src", "index.js"), 1024)
        nm = os.path.join(proj, "node_modules")
        for pkg in PACKAGES:
            write(os.path.join(nm, pkg, "package.json"), 300)
            write(os.path.join(nm, pkg, "index.js"), 2048)
        write(os.path.join(nm, "alpha", "node_modules", "inner", "index.js"), 512)
    print(root)


if __name__ == "__main__":
    main()
